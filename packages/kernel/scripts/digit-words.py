# Generates src/outflow/digit-words.ts: the words for 0-9 in every language num2words knows, plus hand tables for
# languages it lacks.
# Run: uv run --with num2words python -I packages/kernel/scripts/digit-words.py
import sys
import unicodedata
from pathlib import Path

from num2words import CONVERTER_CLASSES, num2words


def fold(word):
    # Same folding as spelled.ts: lowercase, apostrophes dropped, marks removed after a Latin or Greek letter only (Indic vowel signs stay).
    out = []
    latin = False
    for c in unicodedata.normalize("NFD", word.lower()):
        if c in "'\u2019\u02bc":
            continue
        if unicodedata.category(c).startswith("M") and latin:
            continue
        latin = unicodedata.name(c, "").startswith(("LATIN", "GREEK"))
        out.append(c)
    return unicodedata.normalize("NFC", "".join(out))


def one_word(w):
    # A single token of 2+ letters; under 2 letters it would turn ordinary text into digits.
    return len(w) >= 2 and all(unicodedata.category(c)[0] in "LM" for c in w)


# num2words has no Greek or Hindi: written by hand, every common spelling of each digit.
HAND = {
    "el": [["μηδέν"], ["ένα"], ["δύο"], ["τρία"], ["τέσσερα"], ["πέντε"], ["έξι"], ["επτά", "εφτά"], ["οκτώ", "οχτώ"], ["εννέα", "εννιά"]],
    "hi": [["शून्य"], ["एक"], ["दो"], ["तीन"], ["चार"], ["पाँच", "पांच"], ["छह", "छः"], ["सात"], ["आठ"], ["नौ"]],
}

words = {}  # word -> set of digits
langs = []
for lang, table in HAND.items():
    langs.append(lang + " (hand)")
    for digit, spellings in enumerate(table):
        for w in spellings:
            assert one_word(fold(w)), w
            words.setdefault(fold(w), set()).add(digit)
for lang in sorted(CONVERTER_CLASSES):
    got = {}
    for digit in range(10):
        try:
            got[digit] = fold(num2words(digit, lang=lang))
        except Exception as e:
            print(f"skip {lang} {digit}: {type(e).__name__}", file=sys.stderr)
    ok = {d: w for d, w in got.items() if one_word(w)}
    for d, w in got.items():
        if d not in ok:
            print(f"skip {lang} {d}: {got[d]!r} is not one word of 2+ letters", file=sys.stderr)
    if ok:
        langs.append(lang)
    for d, w in ok.items():
        words.setdefault(w, set()).add(d)

dropped = sorted(w for w, ds in words.items() if len(ds) > 1)
table = sorted((w, next(iter(ds))) for w, ds in words.items() if len(ds) == 1)

out = ["// Generated by scripts/digit-words.py: do not edit.",
       f"// Languages ({len(langs)}): {', '.join(langs)}.",
       f"// Dropped, one word for two digits: {', '.join(dropped) or 'none'}.",
       "export const DIGIT_WORDS: Record<string, number> = {"]
out += [f'  "{w}": {d},' for w, d in table]
out.append("};")
Path(__file__).resolve().parent.parent.joinpath("src/outflow/digit-words.ts").write_text("\n".join(out) + "\n")
print(f"{len(table)} words, {len(langs)} languages, dropped: {dropped}", file=sys.stderr)
